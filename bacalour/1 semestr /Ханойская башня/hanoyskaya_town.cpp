#include <iostream>
using namespace std;
int a[5] = { 5, 4, 3, 2, 1 };//массив из пяти элементов отвечает за 1 стержень
int b[5] = { 0 };//массив для второго стержня
int c[5] = { 0 };//массив для третьего стержня
//Создаём три переменные, которые показывают количество колец на каждом стержне.
int countA = 5, countB = 0, countC = 0;
//Эта функция отвечает за визуализацию башни, то есть за вывод колец звёздочками.
void show()
{
    for (int i = 4; i >= 0; i--)//Создаём цикл, который перебирает пять уровней башни сверху вниз
    {
        for (int j = 1; j <= 3; j++)//Внутренний цикл перебирает три стержня.
        {
            int disk = 0;//Она будет хранить размер кольца на текущем уровне.
            //Проверяем, какой стержень сейчас рассматриваем и есть ли на нём кольцо на данном уровне.
            if (j == 1 && i < countA)
                disk = a[i];
            if (j == 2 && i < countB)
                disk = b[i];
            if (j == 3 && i < countC)
                disk = c[i];
            //Если кольца нет, выводим вертикальную черту |.
            if (disk == 0)
            {
                cout << "     |     ";
            }
            else
            {
                //Если кольцо есть, рассчитываем количество звёздочек
                int stars = disk * 2 - 1;
                //Вычисляем количество пробелов слева и справа от кольца.
                int space = (11 - stars) / 2;
                //Выводим пробелы перед звёздочками.
                for (int k = 0; k < space; k++)
                    cout << " ";
                //Выводим нужное количество звёздочек.
                for (int k = 0; k < stars; k++)
                    cout << "*";
                //Добавляем пробелы после звёздочек, чтобы кольцо было расположено по центру.
                for (int k = 0; k < space; k++)
                    cout << " ";
            }
            //Добавляем три пробела между стержнями, чтобы они не сливались.
            cout << "   ";
        }
        cout << endl;
    }

    cout << "-----------   -----------   -----------" << endl;
    cout << "     1             2             3" << endl;
}

void han(int n, int start, int point, int temp)
{
    if (n <= 0)
        return;
    //Перемещаем n - 1 колец с начального стержня на вспомогательный.
    han(n - 1, start, temp, point);
    //Создаём переменную disk, в которой будем хранить номер перемещаемого кольца.
    int disk;
    //Определяем, с какого стержня нужно забрать кольцо.
    if (start == 1)
        disk = a[--countA];
    if (start == 2)
        disk = b[--countB];
    if (start == 3)
        disk = c[--countC];
    //Помещаем кольцо на нужный стержень.
    if (point == 1)
        a[countA++] = disk;
    if (point == 2)
        b[countB++] = disk;
    if (point == 3)
        c[countC++] = disk;
    cout << endl;
    //Выводим информацию о перемещении кольца.
    cout << start << " => " << point << endl;
    //Вызываем функцию визуализации.
    show();
    //Перемещаем оставшиеся n - 1 колец со вспомогательного стержня на конечный.
    han(n - 1, temp, point, start);
}

int main()
{
    //Выводим надпись «Начальное положение».
    cout << "Initial position:" << endl;
    show();
    han(5, 1, 3, 2);
    cout << endl;
    cout << "All disks moved!" << endl;
    return 0;
}
