/*
Дано: Числа последовательности целых чисел вводятся с клавиатуры
до тех пор пока не будет введен 0, тоесть 0 является признаком
окончания последовательности. проверить упорядочены ли значения 
по возрастанию
Анализ:
1.Цикл поисковый и есть 2 причины окончания:
введен 0 и ввод закончен
при проверке двух соседних элементов а и b 
найдено нарушение знака (а < b)
и этот факт фиксирует флажок
2. bool f = true
(предположим что последовательности отсортирована)
3. в этой задаче флажок сложный тоесть f проверки (a < b)
и &&f;
4 в while((a!=b)&&(f = true)&&(b!=0))
5. a = 0, bool f = true if (a!=0)
cin >> b
while (a!=b && f = true && b!=0)
a = b */

#include <iostream>
#include <locale>
using namespace std;

int main()
{
    setlocale(LC_ALL, "65.001"); 
    
    int a;
    bool f = true;
    cin >> a;
    
    if (a != 0)
    {
        int b;
        cin >> b;
        
        // Проверяем первые два элемента (если второе число не 0)
        f = (a < b) && f; 
        
        // Цикл работает, пока не встретим 0
        while (b != 0) 
        {
            /* Если флаг стал false (нарушен порядок), мы все равно должны прочитать остаток чисел до нуля, 
            чтобы программа не зависла. */
            
            if (f) 
            {
                // Если пока всё хорошо, читаем дальше
                a = b;
                cin >> b;
				if (b != 0)
				{
					// Проверяем новую пару
                f = (a < b) && f; 
				}
                
            }
            else 
            {
                /* Если порядок уже нарушен, просто дочитываем числа, пока не дойдем до 0. Флаг f уже false, его менять не надо. */
                cin >> b;
            }
        }
        
        if (f)
        {
            cout << "Все хорошо"; 
        }
        else 
        {
            cout << "Условие не выполнилось";
        }
    }
    else 
    {
        cout << "Нет элементов";
    }

    return 0;
}
